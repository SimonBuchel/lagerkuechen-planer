			Allergenliste – <strong>keine Klarnamen, keine Freitext-Gesundheitsdaten</strong>.
		</li>
		<li>Zahlungsabwicklung über Stripe (inkl. TWINT). Wir speichern keine Kartendaten.</li>
	</ul>

	<h2>Gesundheitsdaten &amp; Minderjährige</h2>
	<p>
		Allergiedaten sind besonders schützenswerte Personendaten und betreffen meist Minderjährige. Die
		Erfassung erfolgt nur mit dokumentierter Einwilligung. Die Zuordnung von Pseudonym zu Klarname
		bleibt bei der Lagerleitung auf Papier und wird nicht im System gespeichert.
	</p>

	<h2>Aufbewahrung &amp; automatische Löschung</h2>
	<p>
		Personendaten eines Lagers werden <strong>90 Tage nach Lagerende automatisch gelöscht</strong>,
		mit einer Vorwarnung per E-Mail. Rezepte und Vorlagen bleiben erhalten.
	</p>


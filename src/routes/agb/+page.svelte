	<p>
		Die vom Tool erzeugten Allergen-Hinweise sind eine Hilfe, keine Garantie. Die Verantwortung für
		die tatsächliche Verpflegung – insbesondere bei Anaphylaxie, Kreuzkontamination und
		Notfallmedikation – liegt vollständig bei der Lagerleitung. Rücksprache mit den Eltern bzw.
		Erziehungsberechtigten ist zwingend.
	</p>

	<h2>3. Rezepte</h2>
	<p>
		Zutatenmengen sind Richtwerte. Die Zubereitungstexte sind eigene, kurze Anleitungen; sie stammen
		nicht aus fremden Kochbüchern oder Websites.
	</p>

	<h2>4. Haftungsausschluss</h2>
	<p>
		Wir haften nicht für Schäden aus der Nutzung des Tools, soweit gesetzlich zulässig. Insbesondere
		wird keine Gewähr für Vollständigkeit oder Richtigkeit der Mengen-, Allergen- und
		Budgetberechnungen übernommen.
	</p>

	<h2>5. Preise &amp; Zahlung</h2>
	<p>
		Kostenpflichtige Funktionen werden vor dem Kauf ausgewiesen. Zahlung über Stripe (Karte/TWINT)
		oder QR-Rechnung.
	</p>

